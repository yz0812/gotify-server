import React from 'react';
import {useParams} from 'react-router';
import {Markdown} from '../common/Markdown';
import {material} from '@uiw/codemirror-theme-material';
import CodeMirror from '@uiw/react-codemirror';
import Info from '@mui/icons-material/InfoOutlined';
import Build from '@mui/icons-material/BuildOutlined';
import Subject from '@mui/icons-material/Subject';
import Refresh from '@mui/icons-material/Refresh';
import Button from '@mui/material/Button';
import IconButton from '@mui/material/IconButton';
import Tooltip from '@mui/material/Tooltip';
import Box from '@mui/material/Box';
import Divider from '@mui/material/Divider';
import {alpha} from '@mui/material/styles';
import Typography from '@mui/material/Typography';
import DefaultPage from '../common/DefaultPage';
import * as config from '../config';
import Container from '../common/Container';
import {IPlugin} from '../types';
import LoadingSpinner from '../common/LoadingSpinner';
import {useStores} from '../stores';
import {useTranslation} from '../i18n';

const PluginDetailView = () => {
    const {id} = useParams<{id: string}>();
    const pluginID = parseInt(id as string, 10);
    const {pluginStore} = useStores();
    const {t} = useTranslation();
    const [currentConfig, setCurrentConfig] = React.useState<string>();
    const [displayText, setDisplayText] = React.useState<string>();

    const pluginInfo = pluginStore.getByIDOrUndefined(pluginID);

    const refreshFeatures = async () => {
        await pluginStore.refreshIfMissing(pluginID);
        await Promise.all([refreshConfigurer(), refreshDisplayer()]);
    };

    React.useEffect(() => void refreshFeatures(), [pluginID]);

    const refreshConfigurer = async () => {
        if (pluginInfo?.capabilities.indexOf('configurer') !== -1) {
            setCurrentConfig(await pluginStore.requestConfig(pluginID));
        }
    };

    const refreshDisplayer = async () => {
        if (pluginInfo?.capabilities.indexOf('displayer') !== -1) {
            setDisplayText(await pluginStore.requestDisplay(pluginID));
        }
    };

    if (pluginInfo == null) {
        return <LoadingSpinner />;
    }

    const handleSaveConfig = async (newConfig: string) => {
        await pluginStore.changeConfig(pluginID, newConfig);
        await refreshFeatures();
    };

    return (
        <DefaultPage title={pluginInfo.name} maxWidth={1000}>
            <PanelWrapper name={t('Plugin Info')} className="plugin-info" icon={Info}>
                <PluginInfo pluginInfo={pluginInfo} />
            </PanelWrapper>
            {pluginInfo.capabilities.indexOf('configurer') !== -1 ? (
                <PanelWrapper
                    name={t('Configurer')}
                    className="configurer"
                    description={t('This is the configuration panel for this plugin.')}
                    icon={Build}
                    refresh={refreshConfigurer}>
                    <ConfigurerPanel
                        pluginInfo={pluginInfo}
                        initialConfig={currentConfig != null ? currentConfig : t('Loading...')}
                        save={handleSaveConfig}
                    />
                </PanelWrapper>
            ) : null}{' '}
            {pluginInfo.capabilities.indexOf('displayer') !== -1 ? (
                <PanelWrapper
                    name={t('Displayer')}
                    className="displayer"
                    description={t('This is the information generated by the plugin.')}
                    refresh={refreshDisplayer}
                    icon={Subject}>
                    <DisplayerPanel
                        pluginInfo={pluginInfo}
                        displayText={displayText != null ? displayText : t('Loading...')}
                    />
                </PanelWrapper>
            ) : null}
        </DefaultPage>
    );
};

interface IPanelWrapperProps {
    name: string;
    className: string;
    description?: string;
    refresh?: () => Promise<void>;
    icon?: React.ComponentType;
}

const PanelWrapper: React.FC<React.PropsWithChildren<IPanelWrapperProps>> = ({
    name,
    className,
    description,
    refresh,
    icon,
    children,
}) => {
    const Icon = icon;
    const {t} = useTranslation();
    return (
        <div style={{width: '100%'}}>
            <Container style={{display: 'block', width: '100%'}}>
                <Box sx={{display: 'flex', alignItems: 'center', gap: 1.5}}>
                    {Icon ? (
                        <Box
                            sx={(theme) => ({
                                display: 'flex',
                                padding: 1,
                                borderRadius: 2,
                                color: theme.palette.primary.main,
                                backgroundColor: alpha(theme.palette.primary.main, 0.1),
                            })}>
                            <Icon />
                        </Box>
                    ) : null}
                    <Box sx={{flex: 1}}>
                        <Typography variant="h6">{name}</Typography>
                        {description ? (
                            <Typography variant="body2" sx={{color: 'text.secondary'}}>
                                {description}
                            </Typography>
                        ) : null}
                    </Box>
                    {refresh ? (
                        <Tooltip title={t('Refresh')}>
                            <IconButton
                                onClick={() => {
                                    refresh();
                                }}>
                                <Refresh />
                            </IconButton>
                        </Tooltip>
                    ) : null}
                </Box>
                <Divider sx={{my: 2}} />
                <div className={className}>{children}</div>
            </Container>
        </div>
    );
};

interface IConfigurerPanelProps {
    pluginInfo: IPlugin;
    initialConfig: string;
    save: (newConfig: string) => Promise<void>;
}
const ConfigurerPanel = ({initialConfig, save}: IConfigurerPanelProps) => {
    const {t} = useTranslation();
    const [unsavedChanges, setUnsavedChanges] = React.useState<string | null>(null);
    const onChange = React.useCallback(
        (value: string | null) => {
            let newConf: string | null = value;
            if (value === initialConfig) {
                newConf = null;
            }
            setUnsavedChanges(newConf);
        },
        [initialConfig]
    );
    return (
        <div>
            <Box sx={{borderRadius: 2, overflow: 'hidden', mb: 2}}>
                <CodeMirror value={initialConfig} theme={material} onChange={onChange} />
            </Box>
            <Button
                variant="contained"
                color="primary"
                fullWidth={true}
                disabled={unsavedChanges === null || unsavedChanges === initialConfig}
                className="config-save"
                onClick={() => {
                    const newConfig = unsavedChanges;
                    save(newConfig!).then(() => {
                        setUnsavedChanges(null);
                    });
                }}>
                <Typography variant="button">{t('Save')}</Typography>
            </Button>
        </div>
    );
};

interface IDisplayerPanelProps {
    pluginInfo: IPlugin;
    displayText: string;
}
const DisplayerPanel: React.FC<IDisplayerPanelProps> = ({displayText}) => (
    <Typography variant="body2">
        <Markdown>{displayText}</Markdown>
    </Typography>
);

interface IPluginInfo {
    pluginInfo: IPlugin;
}

const InfoLine: React.FC<React.PropsWithChildren<{label: string; className?: string}>> = ({
    label,
    className,
    children,
}) => (
    <Typography variant="body2" className={className} sx={{display: 'flex', gap: 1, py: 0.5}}>
        <Box component="b" sx={{minWidth: 140, color: 'text.secondary', fontWeight: 500}}>
            {label}
        </Box>
        {children}
    </Typography>
);

const PluginInfo = ({pluginInfo}: IPluginInfo) => {
    const {name, author, modulePath, website, license, capabilities, id, token} = pluginInfo;
    const {t} = useTranslation();

    return (
        <div style={{wordWrap: 'break-word'}}>
            {name ? (
                <InfoLine label={t('Name')} className="name">
                    <span>{name}</span>
                </InfoLine>
            ) : null}
            {author ? (
                <InfoLine label={t('Author')} className="author">
                    <span>{author}</span>
                </InfoLine>
            ) : null}
            <InfoLine label={t('Module Path')} className="module-path">
                <span>{modulePath}</span>
            </InfoLine>
            {website ? (
                <InfoLine label={t('Website')} className="website">
                    <span>{website}</span>
                </InfoLine>
            ) : null}
            {license ? (
                <InfoLine label={t('License')} className="license">
                    <span>{license}</span>
                </InfoLine>
            ) : null}
            <InfoLine label={t('Capabilities')} className="capabilities">
                <span>{capabilities.join(', ')}</span>
            </InfoLine>
            {capabilities.indexOf('webhooker') !== -1 ? (
                <InfoLine label={t('Custom Route Prefix')}>
                    {((url) => (
                        <a
                            href={url}
                            target="_blank"
                            rel="noopener noreferrer"
                            className="custom-route">
                            {url}
                        </a>
                    ))(`${config.get('url')}plugin/${id}/custom/${token}/`)}
                </InfoLine>
            ) : null}
        </div>
    );
};

export default PluginDetailView;
